import { expect, test } from '@playwright/test';
import { navigateTo, signIn } from './shell.js';
import { SPEECH_SAFE_FAILURE_MESSAGE } from '../src/voice/index.js';

test('Voice simulation reviews drafts, confirms numbers separately and refuses public patient output', async ({ page }) => {
  await signIn(page);
  await navigateTo(page, 'Voice dictation');
  const view = page.getByRole('region', { name: 'Voice dictation', exact: true });
  const button = (name) => view.getByRole('button', { name, exact: true });
  const approve = button('Approve and save review (simulation)');
  const status = view.getByRole('status');
  await expect(view.getByText('Simulation only. No microphone is used and no audio is recorded, stored or sent. Dictation uses fixed fictional scripts. Human review required.')).toBeVisible();
  async function capture(fixture) {
    await view.getByLabel('Dictation script').selectOption(fixture);
    await button('Start listening (simulation)').focus();
    await page.keyboard.press('Enter');
    await expect(button('Stop listening')).toBeFocused();
    await expect(view.getByText('Simulated listening. No microphone is in use.')).toBeVisible();
    await page.keyboard.press('Enter');
    await expect(view.getByRole('heading', { name: 'Transcript review' })).toBeFocused();
  }
  await capture('clear');
  await page.keyboard.press('Tab');
  await expect(view.getByLabel('Your edit')).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(approve).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(button('Start new dictation')).toBeFocused();
  await expect(view.getByRole('region', { name: 'Saved review metadata' })).toContainText('Saved. Reviewed by Alex Morgan');
  await expect(view.getByRole('region', { name: 'Saved review metadata' })).toContainText('0 confirmed numbers. Transcript text is not stored.');
  await expect(view.getByText('Fictional handover draft for review.', { exact: true })).toHaveCount(0);
  await button('Start new dictation').click();
  await expect(button('Start listening (simulation)')).toBeFocused();
  await capture('uncertain');
  await expect(status).toHaveText(SPEECH_SAFE_FAILURE_MESSAGE);
  await expect(approve).toBeDisabled();
  await button('Repeat dictation').click();
  await expect(button('Stop listening')).toBeFocused();
  await button('Cancel').click();
  await expect(button('Start new dictation')).toBeFocused();
  await expect(status).toHaveText('Dictation cancelled. Nothing saved.');
  await button('Start new dictation').click();
  await capture('numeric');
  await expect(approve).toBeDisabled();
  await expect(view.getByText('Transcript review does not confirm numbers')).toBeVisible();
  await expect(view.getByText('Teen/ty confusables: thirteen')).toBeVisible();
  await view.getByLabel('Your edit').fill('Fictional thirteen and thirty');
  await expect(view.getByText('Missing units: detected')).toBeVisible();
  await view.getByLabel('Value label').focus();
  await page.keyboard.type('Fictional value');
  await page.keyboard.press('Tab'); await page.keyboard.type('13');
  await page.keyboard.press('Tab'); await page.keyboard.type('/min');
  await page.keyboard.press('Tab'); await page.keyboard.type('thirteen');
  await page.keyboard.press('Tab');
  await expect(button('Confirm value')).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(approve).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(button('Start new dictation')).toBeFocused();
  await expect(view.getByRole('region', { name: 'Saved review metadata' })).toContainText('1 confirmed numbers. Transcript text is not stored.');
  await expect(view.getByLabel('Your edit')).toHaveCount(0);
  await view.getByLabel('Output mode').selectOption('device');
  await view.getByLabel('Output content').selectOption('patient');
  await button('Preview speech output').click();
  await expect(status).toHaveText('Action refused: Patient information cannot use device output');
  await expect(view.getByLabel('Output mode')).toBeFocused();
  await view.getByLabel('Output mode').selectOption('disabled');
  await button('Preview speech output').click();
  await expect(status).toContainText('Speech output is disabled');
  await expect(view.getByText('No audio is produced. Mode: disabled. Simulation only.')).toBeVisible();
  for (const width of [320, 860]) {
    await page.setViewportSize({ width, height: 900 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await button('Start new dictation').click();
    await capture('numeric');
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await button('Cancel').click();
    await expect(button('Start new dictation')).toBeFocused();
  }
});
